#!/usr/bin/env python3
"""Generate the two V6 main-text tables from archived summary CSVs.

Uses the standard library. Run from any directory. The four output fragments
contain presentation-only rounding of the existing participant-equal results.
"""

import argparse
import math
from pathlib import Path

from table_helpers import MODES, index, md_table, pair, read

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT / "outputs/summaries"
OUTPUT = ROOT / "outputs/tables"
RANGES = ("12", "40")
CONFIGURATIONS = (
    ("PPG only (R0)", "仅 PPG（R0）", "Linear", "线性"),
    ("PPG only (R0)", "仅 PPG（R0）", "MLP", "MLP"),
    ("Early fusion (R1)", "早融合（R1）", "Linear", "线性"),
    ("Early fusion (R1)", "早融合（R1）", "MLP", "MLP"),
    ("Feature fusion (R2)", "特征融合（R2）", "Linear", "线性"),
    ("Feature fusion (R2)", "特征融合（R2）", "MLP", "MLP"),
)
ACTIVITIES = (
    ("Transition", "过渡"),
    ("Sitting", "坐姿"),
    ("Stairs", "楼梯"),
    ("Table soccer", "桌上足球"),
    ("Cycling", "骑行"),
    ("Driving", "驾驶"),
    ("Lunch break", "午休"),
    ("Walking", "步行"),
    ("Working", "工作"),
)
LABELS = ("R0-L", "R0-M", "R1-L", "R1-M", "R2-L", "R2-M")


def load_results():
    overall = index(
        [row for row in read(ARCHIVE / "core/overall_summary.csv")
         if row["weighting"] == "participant_equal"],
        ("endpoint", "mode"),
    )
    activity = index(
        [row for row in read(ARCHIVE / "activity/activity_summary.csv")
         if row["weighting"] == "participant_equal"],
        ("endpoint", "activity_code", "mode"),
    )
    costs = index(read(ARCHIVE / "core/model_complexity.csv"), ("mode",))
    assert set(overall) == {(budget, mode) for budget in RANGES for mode in MODES}
    assert set(activity) == {
        (budget, str(code), mode)
        for budget in RANGES for code in range(9) for mode in MODES
    }
    assert set(costs) == {(mode,) for mode in MODES}
    for row in list(overall.values()) + list(activity.values()):
        assert all(math.isfinite(float(row[key])) and float(row[key]) >= 0
                   for key in ("mae_bpm_mean", "mae_bpm_sd_ddof0"))
    counts = []
    for code in range(9):
        observed = {
            (int(activity[budget, str(code), mode]["n"]),
             int(activity[budget, str(code), mode]["n_people"]))
            for budget in RANGES for mode in MODES
        }
        assert len(observed) == 1
        windows, people = observed.pop()
        assert people == (14 if code in (6, 7, 8) else 15)
        counts.append(windows)
    assert sum(counts) == 64697
    return overall, activity, costs, counts


def overall_fragments(overall, costs):
    best = {
        budget: min(float(overall[budget, mode]["mae_bpm_mean"]) for mode in MODES)
        for budget in RANGES
    }
    tex_rows, chinese_rows = [], []
    for mode, (design, design_zh, head, head_zh) in zip(MODES, CONFIGURATIONS):
        tex_scores, chinese_scores = [], []
        for budget in RANGES:
            score = overall[budget, mode]
            tex_score = pair(score)
            chinese_score = pair(score, tex=False)
            if float(score["mae_bpm_mean"]) == best[budget]:
                tex_score = r"$\mathbf{" + tex_score[1:-1] + "}$"
                chinese_score = "**" + chinese_score + "**"
            tex_scores.append(tex_score)
            chinese_scores.append(chinese_score)
        cost = costs[mode,]
        parameters = f"{int(cost['parameters']):,}"
        macs = f"{int(cost['conv_linear_macs']) / 1_000_000:.3f}"
        tex_rows.append(" & ".join([design, head] + tex_scores + [parameters, macs]) + r" \\")
        chinese_rows.append([design_zh, head_zh] + chinese_scores + [parameters, macs])
    tex = r"""% Generated by scripts/paper/build_v6_main_tables.py.
% Sources: core/overall_summary.csv and core/model_complexity.csv.
\begin{table}[htbp]
\centering
\caption{Overall MAE and model cost.}
\label{tab:overall}
\begingroup
\fontsize{11}{13}\selectfont
\setlength{\tabcolsep}{5pt}
\begin{tabular}{@{}llrrrr@{}}
\toprule
Input design & Head & \shortstack{MAE (bpm)\\Epochs 1--12} &
\shortstack{MAE (bpm)\\Epochs 1--40} & Parameters & \shortstack{MAC/window\\($10^6$)} \\
\midrule
""" + "\n".join(tex_rows) + r"""
\bottomrule
\end{tabular}
\endgroup
\par\smallskip
\begin{minipage}{\linewidth}\fontsize{10.5}{12.5}\selectfont
MAE values are the mean $\pm$ standard deviation (SD) across five participant-equal seed estimates (divisor 5).
Bold marks the lowest mean in each checkpoint-selection range.
Parameter counts include biases. MAC counts are per 8-second window and include
convolutional and linear layers only, with one multiply--accumulate counted as one MAC.
\end{minipage}
\end{table}
"""
    chinese = "表 1　总体 MAE 与模型开销\n\n" + md_table(
        ["输入设计", "回归头", "1–12 轮 MAE（bpm）", "1–40 轮 MAE（bpm）", "参数量", "每窗 MAC（百万）"],
        chinese_rows,
    )
    chinese += (
        "\n\nMAE 为人员等权的五种子均值 ± 标准差（SD），标准差除数为 5。"
        "粗体表示各选模范围中最低的平均 MAE。参数量包括偏置。"
        "MAC 按每个 8 秒输入窗统计，只计卷积层与线性层，一次乘加计为一个 MAC。\n"
    )
    return tex, chinese


def activity_fragments(activity, counts):
    tex_rows, chinese_panels = [], []
    for budget in RANGES:
        tex_rows.append(
            r"\midrule\multicolumn{7}{l}{\textit{Checkpoint selection within epochs 1--"
            + budget + r"}}\\"
        )
        chinese_rows = []
        for code, (name, name_zh) in enumerate(ACTIVITIES):
            cells = [activity[budget, str(code), mode] for mode in MODES]
            best = min(float(cell["mae_bpm_mean"]) for cell in cells)
            tex_scores, chinese_scores = [], []
            for cell in cells:
                tex_score = pair(cell).replace(r"\pm", r"{\pm}")
                chinese_score = pair(cell, tex=False)
                if float(cell["mae_bpm_mean"]) == best:
                    tex_score = r"$\mathbf{" + tex_score[1:-1] + "}$"
                    chinese_score = "**" + chinese_score + "**"
                tex_scores.append(tex_score)
                chinese_scores.append(chinese_score)
            tex_rows.append(" & ".join([name] + tex_scores) + r" \\")
            chinese_rows.append([name_zh] + chinese_scores)
        chinese_panels.append(
            f"**第 1–{budget} 轮内选模**\n\n"
            + md_table(["活动"] + list(LABELS), chinese_rows)
        )
    count_names = ("Transition", "Sitting", "Stairs", "Soccer", "Cycling", "Driving", "Lunch", "Walking", "Working")
    count_tex = " & ".join([""] + list(count_names)) + r" \\" + "\n"
    count_tex += " & ".join(["Windows"] + [f"{n:,}" for n in counts]) + r" \\"
    tex = r"""% Generated by scripts/paper/build_v6_main_tables.py.
% Source: activity/activity_summary.csv, participant_equal rows only.
\begin{table}[htbp]
\centering
\caption{MAE by activity.}
\label{tab:activity}
\begingroup
\fontsize{10.5}{12.5}\selectfont
\setlength{\tabcolsep}{4.5pt}
\begin{tabular}{@{}lrrrrrr@{}}
\toprule
Activity & R0-L & R0-M & R1-L & R1-M & R2-L & R2-M \\
""" + "\n".join(tex_rows) + r"""
\bottomrule
\end{tabular}
\par\smallskip
\setlength{\tabcolsep}{2.5pt}
\begin{tabular}{@{}lrrrrrrrrr@{}}
""" + count_tex + r"""
\end{tabular}
\par\smallskip
\begin{minipage}{\linewidth}
L and M denote linear and MLP heads. MAE is in bpm, with mean $\pm$ standard deviation (SD) across
five seeds (divisor 5). Bold marks the lowest unrounded mean among all six
configurations in each activity and selection range; it does not denote significance.
Within each activity, participants with recorded windows receive equal weight.
Lunch break, walking and working include 14 participants each, and all other
activities include 15. These activity comparisons are descriptive and post hoc.
\end{minipage}
\endgroup
\end{table}
"""
    chinese = "表 2　各活动的 MAE\n\n" + "\n\n".join(chinese_panels)
    chinese += "\n\n" + md_table(
        ["活动"] + [zh for _, zh in ACTIVITIES],
        [["窗数"] + [f"{n:,}" for n in counts]],
    )
    chinese += (
        "\n\nL、M 分别表示线性头和 MLP 头。MAE 单位为 bpm，"
        "数值为五种子的均值 ± 标准差，标准差除数为 5。"
        "粗体表示每类活动及选模范围内六配置中未舍入均值最低者，不表示统计显著。"
        "每类活动内，对有记录的参与者等权平均。午休、步行和工作各有 14 人，"
        "其余活动各有 15 人。活动比较为事后描述性分析。\n"
    )
    return tex, chinese


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT)
    args = parser.parse_args()
    overall, activity, costs, counts = load_results()
    fragments = {
        "overall_table": overall_fragments(overall, costs),
        "activity_table": activity_fragments(activity, counts),
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, (tex, chinese) in fragments.items():
        (args.output_dir / (name + ".tex")).write_text(tex, encoding="utf-8")
        (args.output_dir / (name + ".md")).write_text(chinese, encoding="utf-8")
    print(f"Wrote 6 overall rows and 18 activity rows to {args.output_dir}.")


if __name__ == "__main__":
    main()
